// Generated into `docs/tracking/reviewer-qualification/oracles/` by `generate.ts`; the JSON is never hand-edited.
import type { Oracle, OracleSet } from './cases.js';
import { v3CaseId } from './case-set-v3.js';
import { ORACLES_V2 } from './oracles-v2.js';

/** Version two's note for a renamed graph copy, which names the case it copies — and version three's. */
const RENAMED_GRAPH_V2 =
	'A renamed copy of G2-CLEAN: the architecture’s and every type’s names differ, in the graph and in the account; nothing else does.';
const RENAMED_GRAPH_V3 =
	'A renamed copy of G3-CLEAN: the architecture’s and every type’s names differ, in the graph and in the account; nothing else does.';
/** What the clean graph case's note adds in version three — the two changes. */
const CLEAN_GRAPH_V3 =
	' Version three (REG-D-081): the design type’s scope takes in the foundations, and the permit submission also ' +
	'receives the geotechnical report and the design calculations.';

/** A version-two note, as version three states it. */
function noteOf(o: Oracle, caseId: string): string {
	if (o.note === RENAMED_GRAPH_V2) return RENAMED_GRAPH_V3;
	if (caseId === 'G3-CLEAN') return `${o.note}${CLEAN_GRAPH_V3}`;
	return o.note;
}

function carried(o: Oracle): Oracle {
	const caseId = v3CaseId(o.caseId);
	return { ...o, caseId, note: noteOf(o, caseId) };
}

