/** Version one's note for a renamed graph copy, which names the case it copies — and version two's. */
const RENAMED_GRAPH_V1 =
	'A renamed copy of G-CLEAN: the architecture’s and every type’s names differ, in the graph and in the account; nothing else does.';
const RENAMED_GRAPH_V2 =
	'A renamed copy of G2-CLEAN: the architecture’s and every type’s names differ, in the graph and in the account; nothing else does.';
/** What the clean graph case's note adds in version two — the routing the correction made. */
const CLEAN_GRAPH_V2 =
	' Version two (REG-F-449): the geotechnical report also reaches the structural-form options study and the ' +
	'independent check.';

/** A version-one note, as version two states it. */
function noteOf(o: Oracle, caseId: string): string {
	if (o.note === RENAMED_GRAPH_V1) return RENAMED_GRAPH_V2;
	if (caseId === 'G2-CLEAN') return `${o.note}${CLEAN_GRAPH_V2}`;
	return o.note;
}

function carried(o: Oracle): Oracle {
	const caseId = v2CaseId(o.caseId);
	return { ...o, caseId, note: noteOf(o, caseId) };
}

