import { CASE_SET_V10 } from './case-set-v10.js';
import { CASE_SET_V11 } from './case-set-v11.js';
import type { Oracle, OracleSet, PwaTypeCase } from './cases.js';
import { ORACLES_V10 } from './oracles-v10.js';

const partsOf = (cases: readonly { readonly arm: string }[]): PwaTypeCase[] =>
	cases.filter((c): c is PwaTypeCase => c.arm === 'PWA_TYPE');

/**
 * ⭐ D3d — EACH OF THE 7, BY ITS VERSION-TEN ID: its new id and its source's, both ids of the source. Read off the two case sets,
 * whose part cases are in one order (`case-set-v11.ts` carries version ten's, each in its place): a part case whose id moved is
 * one of the 7.
 */
const PARTS_V11 = partsOf(CASE_SET_V11.cases);
const RENAMED: ReadonlyMap<string, { readonly id: string; readonly source: string; readonly v10Source: string }> = new Map(
	partsOf(CASE_SET_V10.cases).flatMap((ten, i) => {
		const eleven = PARTS_V11[i];
		return eleven === undefined || ten.id === eleven.id
			? []
			: [[ten.id, { id: eleven.id, source: eleven.sourceCaseId, v10Source: ten.sourceCaseId }] as const];
	})
);

/** The source id `id`, where it stands as an id: never inside a longer one (`G10-CLEAN` is not `G10-CLEAN-R1`'s head). */
const asAnId = (id: string): RegExp => new RegExp(`${id.replace(/[.*+?^${}()|[\]\\]/g, String.raw`\$&`)}(?![-A-Za-z0-9])`, 'g');

/**
 * ⭐ D3d — a version-ten oracle as version eleven holds it: one of the 69's, byte for byte; one of the 7's under its case's new
 * id, its verdict, faulted criteria and standing unchanged, and its note version ten's — its body naming its source by the
 * source's new id, the source oracle still given to version seven's case by its own id; then what version ten's note says its
 * source is, unchanged and still true; then what the new source is — version ten's source, restated by D3d — and whose oracle
 * this is.
 */
function carriedToItsNewId(o: Oracle): Oracle {
	const to = RENAMED.get(o.caseId);
	if (to === undefined) return o;
	const said = o.note.indexOf(` ${to.v10Source} is version seven’s `);
	const [body, what] = said < 0 ? [o.note, ''] : [o.note.slice(0, said), o.note.slice(said)];
	return {
		caseId: to.id,
		faulted: o.faulted,
		disposition: o.disposition,
		expectation: o.expectation,
		note:
			body.replace(asAnId(to.v10Source), to.source) +
			what +
			` ${to.source} is version ten’s ${to.v10Source}, restated by D3d (REG-D-133) under a new id (design D3d), and this ` +
			`oracle is version ten’s for ${o.caseId}, carried unchanged.`
	};
}

