// For each case: the criteria it REQUIRES a reviewer to fault, the Reasoning Review disposition expected from
// `composeAssuranceOutcome` over that policy's reference alone, and whether the expectation is UNCONTESTED or THE
// AUTHOR'S CLAIM (`REG-F-427` (4) calls one such verdict "the spec's claim … not a universal one").
//
// ⚠ THE STANDING, AS CONFERRED. Every clean case and its renamed copies are THE AUTHOR'S CLAIM: a clean verdict
// asserts the ABSENCE of all nine failure classes, and no author can make that uncontested — a reviewer that faults
// a clean case may have found something the author missed, so a failure there is escalated with that said. Every
// planted case but one is UNCONTESTED: its defect is built from the criterion's own text and nothing else in the
// case supports it. W-RR-03 is THE AUTHOR'S CLAIM: its load applied over the central 20 m is also a load-arrangement
// choice, which a competent reviewer could fault under RR-06 or RR-07 rather than RR-03.
//
// Correcting an oracle is a new oracle VERSION (a new file beside this one), never an edit, and moves no case digest.
// Generated into `docs/tracking/reviewer-qualification/oracles/` by `generate.ts`; the JSON is never hand-edited.
import type { Oracle, OracleSet, OracleStanding } from './cases.js';

const clean = (caseId: string, note: string): Oracle => ({
	caseId,
	faulted: [],
	disposition: 'SATISFIED',
	expectation: "the author's claim",
	note
});

const planted = (
	caseId: string,
	criterionId: string,
	note: string,
	expectation: OracleStanding = 'uncontested'
): Oracle => ({
	caseId,
	faulted: [criterionId],
	disposition: 'REJECTED',
	expectation,
	note
});

