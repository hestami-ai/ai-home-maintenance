import type { InventoryDocument } from '../contracts/inventory.js';

const code = (value: string | number | boolean | null): string =>
	value === null ? '`—`' : `\`${String(value).replaceAll('`', '\\`')}\``;

const cell = (value: string): string => value.replaceAll('|', '\\|').replaceAll('\r', ' ').replaceAll('\n', ' ');

const list = (values: readonly string[]): string =>
	values.length === 0 ? code('NONE') : values.map((value) => code(value)).join(', ');

const declaredList = (values: readonly string[] | null): string =>
	values === null ? code('ABSENT') : list(values);

export function renderInventoryMarkdown(inventory: InventoryDocument): string {
	const lines: string[] = [];
	lines.push(
		'> Generated by `bun run csaa:inventory`. Do not edit this marked region by hand. The facts below are current only for the exact `subjectId` and selected-file manifest shown here; configured tools are not represented as executed.',
		'',
		'#### Generated subject identity',
		'',
		'| Field | Value | Provenance |',
		'| --- | --- | --- |',
		`| Schema | ${code(inventory.schemaVersion)} | Generator contract |`,
		`| Subject schema | ${code(inventory.subject.schemaVersion)} | DWP-002 subject contract |`,
		`| Generator | ${code(`${inventory.generator.id}@${inventory.generator.version}`)} | Selected generator source is included in the file-manifest digest |`,
		`| Subject kind | ${code(inventory.subject.subjectKind)} | Working-tree file bytes; Git cleanliness is not a prerequisite |`,
		`| Subject ID | ${code(inventory.subject.subjectId)} | Domain-separated file-manifest, configuration, schema, perimeter, and exclusion-policy identity |`,
		`| File-manifest digest | ${code(inventory.subject.fileManifestDigest)} | ${code(`${inventory.subject.selectedFileCount} selected files`)} |`,
		`| Configuration digest | ${code(inventory.subject.configurationDigest)} | Selected files classified as configuration |`,
		`| Repository root | ${code(inventory.subject.repositoryRoot)} | Machine-independent repository-relative identity |`,
		`| Perimeter | ${cell(list(inventory.subject.perimeter))} | Root workspace declaration and configured inventory roots |`,
		`| Resolution completeness | ${code(inventory.subject.resolutionCompleteness)} | Project/configuration diagnostics and generated-context freshness remain explicit |`,
		`| Generated contexts | ${code(inventory.subject.generatedContexts.length)} | Content identity is separate from CURRENT/STALE/UNKNOWN freshness evidence |`,
		'',
		'#### Population accounting',
		'',
		'| Class | Discovered | Included | Excluded | Inventoried | Failed | Provenance |',
		'| --- | ---: | ---: | ---: | ---: | ---: | --- |'
	);
	for (const population of inventory.artifactPopulations) {
		lines.push(
			`| ${code(population.artifactClass)} | ${population.discovered} | ${population.included} | ${population.excluded} | ${population.successfullyInventoried} | ${population.failed} | ${cell(list(population.provenance))} |`
		);
	}
	lines.push('', 'Excluded regions and exact generated outputs remain explicit; unenumerated physical populations stay UNKNOWN so caches and build outputs cannot create false completeness:');
	for (const exclusion of inventory.subject.excludedClasses) {
		lines.push(
			`- ${code(exclusion.id)} — included files: ${code(exclusion.includedFileCount)}; physical count: ${code(exclusion.excludedPhysicalFileCount)} (${code(exclusion.countState)}); policy rules: ${code(exclusion.policyRuleCount)}; state: ${code(exclusion.physicalPopulationState)}; rules: ${list(exclusion.rules)}`
		);
	}

	lines.push(
		'',
		'#### Workspace manifests',
		'',
		'| Kind | Workspace | Path | Private | Scripts | Dependencies | Exports | Provenance |',
		'| --- | --- | --- | --- | ---: | ---: | --- | --- |'
	);
	for (const workspace of inventory.workspaces) {
		lines.push(
			`| ${code(workspace.kind)} | ${code(workspace.name)} | ${code(workspace.path)} | ${code(workspace.private)} | ${Object.keys(workspace.scripts).length} | ${workspace.dependencies.length} | ${code(workspace.exportsState)} | ${cell(list(workspace.provenance))} |`
		);
	}

	lines.push(
		'',
		'#### TypeScript project declarations',
		'',
		'Candidate counts combine the resolved compiler-root population with separately classified framework candidates; semantic Program construction remains deferred.',
		'',
		'| Configuration | Status | Root disposition | Extends | Include | Files | References | Candidate artifacts | Framework candidates | Generated context | Partiality reasons | Diagnostics | Provenance |',
		'| --- | --- | --- | --- | --- | --- | --- | ---: | ---: | --- | --- | --- | --- |'
	);
	for (const project of inventory.typescriptProjects) {
		const extendsCell = project.extends === null || typeof project.extends === 'string'
			? code(project.extends)
			: cell(list(project.extends));
		const generatedContextCell = project.generatedContexts.length === 0
			? code('NONE')
			: cell(project.generatedContexts.map((context) => code(`${context.freshness}: ${context.path}`)).join(', '));
		const partialityCell = project.partialityReasons.length === 0
			? code('NONE')
			: cell(project.partialityReasons.map((reason) => `${code(reason.code)}: ${reason.message}`).join('; '));
		const diagnosticsCell = code(`${project.diagnosticsState}: ${project.diagnostics.length}`);
		lines.push(
			`| ${code(project.path)} | ${code(project.status)} | ${code(project.rootDisposition)} | ${extendsCell} | ${cell(declaredList(project.include))} | ${cell(declaredList(project.files))} | ${cell(list(project.references))} | ${project.candidateArtifactCount} | ${project.frameworkCandidates.length} | ${generatedContextCell} | ${partialityCell} | ${diagnosticsCell} | ${cell(list(project.provenance))} |`
		);
	}

	lines.push(
		'',
		'#### Configured command surfaces',
		'',
		'| Owner | Script | Categories | State | Command | Provenance |',
		'| --- | --- | --- | --- | --- | --- |'
	);
	for (const command of inventory.commands) {
		lines.push(
			`| ${code(command.owner)} | ${code(command.name)} | ${cell(list(command.categories))} | ${code(command.state)} | ${cell(code(command.command))} | ${cell(list(command.provenance))} |`
		);
	}

	lines.push(
		'',
		'#### Dependency boundary and installed providers',
		'',
		`Dependency-cruiser analyzed perimeter: ${list(inventory.dependencyBoundary.analyzedPerimeter)}. Combined enforced product perimeter: ${list(inventory.dependencyBoundary.enforcementPerimeter)} through ${list(inventory.dependencyBoundary.enforcementCarriers)}. State: ${code(inventory.dependencyBoundary.state)}; configuration: ${code(inventory.dependencyBoundary.configurationPath)}; rules: ${list(inventory.dependencyBoundary.ruleIds)}; provenance: ${list(inventory.dependencyBoundary.provenance)}.`,
		'',
		'| Provider | Locked version | Install | Configuration | Gate | CSAA adapter | Implemented adapter capabilities | Potential tool capabilities | Provenance |',
		'| --- | --- | --- | --- | --- | --- | --- | --- | --- |'
	);
	for (const provider of inventory.providers) {
		lines.push(
			`| ${code(provider.name)} | ${code(provider.version)} | ${code(provider.installationState)} | ${code(provider.configurationState)} | ${code(provider.gateState)} | ${code(provider.adapterState)} | ${cell(list(provider.adapterCapabilities))} | ${cell(list(provider.potentialCapabilities))} | ${cell(list(provider.provenance))} |`
		);
	}

	lines.push(
		'',
		'#### Assurance surfaces',
		'',
		'| Surface | Population/configuration | State | Provenance or qualification |',
		'| --- | --- | --- | --- |',
		`| Unit tests | ${code(`${inventory.assuranceSurfaces.unitTests.files.length} files`)} | ${code(inventory.assuranceSurfaces.unitTests.state)} | ${cell(list(inventory.assuranceSurfaces.unitTests.files))} |`,
		`| Deterministic E2E | ${code(`${inventory.assuranceSurfaces.e2e.deterministicFiles.length} files`)} | ${code(inventory.assuranceSurfaces.e2e.state)} | ${cell(list(inventory.assuranceSurfaces.e2e.deterministicFiles))} |`,
		`| Live E2E | ${code(`${inventory.assuranceSurfaces.e2e.liveFiles.length} files`)} | ${code(inventory.assuranceSurfaces.e2e.state)} | ${cell(list(inventory.assuranceSurfaces.e2e.liveFiles))} |`,
		`| Coverage | provider ${code(inventory.assuranceSurfaces.coverage.provider)}; include ${cell(list(inventory.assuranceSurfaces.coverage.include))}; exclude ${cell(list(inventory.assuranceSurfaces.coverage.exclude))} | ${code(inventory.assuranceSurfaces.coverage.state)} | ${code(inventory.assuranceSurfaces.coverage.configurationPath)}; no output ingested |`,
		`| Mutation | ${cell(list(inventory.assuranceSurfaces.mutation.commands))} | ${code(inventory.assuranceSurfaces.mutation.state)} | runner ${code(inventory.assuranceSurfaces.mutation.runnerPath)}; ledger ${code(inventory.assuranceSurfaces.mutation.ledgerPath)} |`
	);

	lines.push(
		'',
		'#### Existing `verif` and `scripts` analyzer estate and migration disposition',
		'',
		'| Path | Content SHA-256 | Role | Extraction | Asserted population | Gate/test carrier | Baseline | Disposition | Provenance |',
		'| --- | --- | --- | --- | --- | --- | --- | --- | --- |'
	);
	for (const asset of inventory.verificationAssets) {
		lines.push(
			`| ${code(asset.path)} | ${code(asset.contentSha256)} | ${code(asset.role)} | ${code(asset.extractionMethod)} | ${cell(asset.assertedPopulation)} | ${cell(list(asset.gateCarriers))} | ${cell(list(asset.associatedBaselines))} | ${code(asset.disposition)} | ${cell(list(asset.provenance))} |`
		);
	}

	lines.push(
		'',
		'#### CSAA capability state',
		'',
		'| Capability | State | Provider | Qualification | Provenance |',
		'| --- | --- | --- | --- | --- |'
	);
	for (const capability of inventory.capabilities) {
		lines.push(
			`| ${code(capability.id)} | ${code(capability.state)} | ${code(capability.provider)} | ${cell(capability.explanation)} | ${cell(list(capability.provenance))} |`
		);
	}

	lines.push('', '#### Explicit unknowns and non-claims', '');
	for (const unknown of inventory.unknowns) {
		lines.push(`- ${unknown.statement} Provenance: ${list(unknown.provenance)}.`);
	}
	lines.push('');
	return lines.join('\n');
}
