"""Triage one or more batch-runner sweeps for the JPWB Sonar cycle.

usage: triage.py <jpwb_root> <anchors.json> <out.json> <outdir1> [<outdir2> ...]
  each outdir holds a batch-runner worklist.json and ledger.json.

Per finding it records: the rule id (short form, e.g. S3776), Sonar's message VERBATIM (never glossed), line/col,
whether a refusal is already RECORDED at the site (the short rule id named in a comment on the line or within the
12 lines above it, or NOSONAR on the line - the repository's form for ruled won't-fixes), whether the file is
GENERATED (fix the generator, not the output), and the file's live mutation-ledger anchors.
It also checks every live anchor in every file the ledger names occurs EXACTLY ONCE now (the baseline), so a later
red can be told apart from one that was already there.
"""
import json
import os
import re
import sys
from collections import Counter, defaultdict

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
root = sys.argv[1].replace("\\", "/").rstrip("/")
anchors = json.load(open(sys.argv[2], encoding="utf-8"))
out_path = sys.argv[3]
outdirs = sys.argv[4:]

work, status = {}, Counter()
for d in outdirs:
    w = json.load(open(os.path.join(d, "worklist.json"), encoding="utf-8"))
    work.update(w["files"])
    led = json.load(open(os.path.join(d, "ledger.json"), encoding="utf-8"))
    for f, r in led.get("results", {}).items():
        status[r.get("status", "?")] += 1
        if r.get("status") != "ok":
            print("  non-ok:", r.get("status"), f.replace(root + "/", ""))

GEN_RE = re.compile(r"(@generated|DO NOT EDIT|AUTO-?GENERATED|GENERATED BY|generated file)", re.I)
CX_RE = re.compile(r"from (\d+) to the (\d+) allowed")
COMMENT_RE = re.compile(r"(//|/\*|^\s*\*)")


def short(rule):
    return str(rule).split(":")[-1]


# Families refused as a whole (every site inspected 2026-11-12); they are recorded centrally, never sent to agents.
FAMILY = {
    "S9382": (lambda m: True, "sequential awaits are deliberate (browser steps, polls, ordered writes): Promise.all would change ordering, concurrency and failure behaviour"),
    "S7750": (lambda m: "findLast" in m, "ES2023 API (.findLast); the lib is ES2022 (scripts/tsconfig.json records the deliberate filter(...).at(-1) form)"),
    "S4036": (lambda m: True, "repository tooling spawns git, bun, python, taskkill, where and which by name on the developer's machine; absolute paths would break portability"),
    "S7503": (lambda m: True, "removing async turns a Promise return into a plain value and a rejection into a synchronous throw; these signatures are interface-shaped"),
    "S7784": (lambda m: True, "structuredClone is not equivalent to a JSON round trip (undefined members, Dates, Maps, prototypes)"),
    "S5332": (lambda m: True, "'http://decision-model.invalid' is a deliberately unresolvable placeholder inside a pinned record identity; nothing is fetched from it"),
}
# Site-specific rulings from earlier cycles that the code does not yet record at the site: keep, and record.
PRIOR = {
    ("verif/arrow-command-census.ts", "S4158"): "EXEMPT is a deliberately empty governed extension point (no .set() anywhere; an exemption list rots into an allowlist, so nothing may be added without a register id) - ruled 2026-08-17",
    ("packages/rph-projections/src/handoff-order.ts", "S4138"): "an intentional breadth-first worklist that pushes to the array it walks; the index loop states that the array grows - ruled 2026-07-24",
    ("apps/rph-demo/src/lib/server/authoring-turn.ts", "S7747"): "the spread is a deliberate snapshot: the loop body deletes from the map it iterates - ruled 2026-07-20",
    ("apps/rph-demo/e2e/phase7-half-b.e2e.ts", "S2925"): "the injected pause of a polling harness: a fixed interval between polls is what it is for (a refusal of this cycle; the 2026-07-20 ruling covered screenshot settle-waits, not this pause)",
    ("apps/rph-demo/e2e/pwa-designer-gallery.e2e.ts", "S2925"): "a settle-wait before a screenshot: there is no observable condition for 'the layout has finished animating' - ruled 2026-07-20",
}


files_out, by_rule, by_tier, cx, audit = {}, defaultdict(Counter), Counter(), [], []
for abs_path in sorted(work):
    items = work[abs_path]
    rel = abs_path.replace(root + "/", "")
    try:
        text = open(abs_path, encoding="utf-8").read()
    except OSError:
        text = ""
    lines = text.split("\n")
    head = "\n".join(lines[:15])
    generated = bool(GEN_RE.search(head))
    live = [a for a in anchors.get(rel, []) if not a["history"]]
    recs = []
    for x in items:
        s = short(x["rule"])
        ln = int(x["line"])
        msg = x.get("message") or ""
        recorded_at = None
        for i in range(ln, max(0, ln - 41), -1):  # the line itself and the 40 lines above it
            w = lines[i - 1] if 0 < i <= len(lines) else ""
            if (s in w and COMMENT_RE.search(w)) or (i == ln and "NOSONAR" in w):
                recorded_at = i
                break
        fam = FAMILY.get(s)
        prior = PRIOR.get((rel, s))
        if recorded_at:
            tier, note = "recorded", "rule named in a comment at L%d" % recorded_at
            audit.append((rel, s, ln, recorded_at, lines[recorded_at - 1].strip()[:110]))
        elif fam and fam[0](msg):
            tier, note = "family", fam[1]
        elif generated:
            tier, note = "gen", ""
        else:
            tier, note = ("C" if s == "S3776" else "AB"), (prior or "")
        m = CX_RE.search(msg)
        if s == "S3776" and m and tier == "C":
            cx.append((int(m.group(1)), rel, ln))
        rec = {"rule": s, "line": ln, "col": x.get("col"), "message": msg, "tier": tier}
        if note:
            rec["note"] = note
        if prior and tier in ("AB", "C"):
            rec["prior"] = prior
        recs.append(rec)
        by_rule[s][tier] += 1
        by_tier[tier] += 1
    if recs:
        files_out[rel] = {"abs": abs_path, "generated": generated, "anchors": [{"id": a["id"], "find": a["find"]} for a in live], "findings": recs}

# Baseline anchor check over every file the ledger names (live entries only).
bad = []
for rel, lst in anchors.items():
    p = root + "/" + rel
    try:
        text = open(p, encoding="utf-8", newline="").read()
    except OSError:
        if any(not a["history"] for a in lst):
            bad.append((rel, "FILE MISSING", ""))
        continue
    for a in lst:
        if a["history"]:
            continue
        n = text.count(a["find"])
        if n != 1:
            bad.append((rel, a["id"], n))

json.dump({"root": root, "files": files_out}, open(out_path, "w", encoding="utf-8"), indent=1)

total = sum(by_tier.values())
print("analysed files:", len(work), "| ledger statuses:", dict(status))
print("findings:", total, "| by tier:", dict(by_tier))
print("files with findings:", len(files_out), "| files with OPEN findings:", sum(1 for f in files_out.values() if any(r["tier"] != "recorded" for r in f["findings"])))
print("\nby rule (open = AB + C + gen; recorded = ruled at the site; family = refused as a whole, recorded centrally):")
for s, c in sorted(by_rule.items(), key=lambda kv: -sum(kv[1].values())):
    open_n = c["AB"] + c["C"] + c["gen"]
    print("  %-7s total %4d  open %4d  recorded %4d  family %4d" % (s, sum(c.values()), open_n, c["recorded"], c["family"]))
print("\nrecorded at the site (audit each: is the comment about THIS finding?):")
for a in audit:
    print("  %s %s L%d <- comment L%d: %s" % a)
prior_n = sum(1 for f in files_out.values() for r in f["findings"] if r.get("prior"))
print("open findings carrying a prior ruling to record:", prior_n)
print("\nopen S3776 (cx, file:line):")
for n, rel, ln in sorted(cx, reverse=True):
    print("  cx=%-4d %s:%d" % (n, rel, ln))
gen_files = [r for r, f in files_out.items() if f["generated"]]
print("\ngenerated files with findings:", gen_files)
print("open-finding files that carry live anchors:", sum(1 for f in files_out.values() if f["anchors"] and any(r["tier"] != "recorded" for r in f["findings"])))
print("\nbaseline anchors NOT exactly once (live entries):", len(bad))
for b in bad[:20]:
    print("  ", b)
